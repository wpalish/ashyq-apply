#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'frontend', 'src', 'styles', 'tokens.css');
const outputPath = path.join(root, 'specs', 'tokens', 'token-reference.md');
const source = fs.readFileSync(sourcePath, 'utf8');

function block(pattern, name) {
  const match = source.match(pattern);
  if (!match?.[1]) throw new Error(`Could not find ${name} token block`);
  return match[1];
}

function declarations(css) {
  return [...css.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map((match) => [
    match[1],
    match[2].replace(/\s+/g, ' ').trim(),
  ]);
}

function cell(value) {
  return `\`${value.replaceAll('|', '\\|')}\``;
}

const light = declarations(block(/:root\s*\{([\s\S]*?)\n\}/, 'light'));
const dark = new Map(declarations(block(/:root\[data-theme='dark'\]\s*\{([\s\S]*?)\n\}/, 'dark')));
const layerOne = light.filter(([name]) => name.startsWith('--ds-'));
const layerTwo = light.filter(([name]) => !name.startsWith('--ds-'));

const lines = [
  '# Token reference',
  '',
  '> Generated by `node scripts/generate-token-reference.js` from `frontend/src/styles/tokens.css`. Layer 1 variables define upstream primitives. Layer 2 variables are the only variables component CSS may reference.',
  '',
  '## Layer 1 — upstream design-system primitives',
  '',
  '| Variable | Default value | Dark override | When to use |',
  '|---|---|---|---|',
  ...layerOne.map(([name, value]) => {
    const purpose = name.startsWith('--ds-color-brand-')
      ? 'Exact brandbook v1.1 primitive. Keep the value exact; components consume its semantic Layer 2 alias.'
      : 'Upstream primitive. Define or theme at the design-system boundary; never reference directly from component CSS.';
    return `| ${cell(name)} | ${cell(value)} | ${dark.has(name) ? cell(dark.get(name)) : '—'} | ${purpose} |`;
  }),
  '',
  '## Layer 2 — ASHYQ Apply project aliases',
  '',
  '| Variable | Value | When to use |',
  '|---|---|---|',
  ...layerTwo.map(([name, value]) => `| ${cell(name)} | ${cell(value)} | Use this project-semantic alias by meaning; never reach through to a ${cell('--ds-*')} primitive from component CSS. |`),
  '',
  '## Consumption contract',
  '',
  '1. Components in `global.css`, `components.css`, and feature CSS reference Layer 2 only.',
  '2. Theme changes override Layer 1; aliases and components remain unchanged.',
  '3. Add a primitive and a semantic alias together. Document the semantic meaning in the relevant foundation or component spec.',
  '4. Run `node scripts/token-audit.js`; zero errors and zero warnings are required.',
];

fs.writeFileSync(outputPath, `${lines.join('\n')}\n`);
console.log(`Wrote ${path.relative(root, outputPath)} with ${layerOne.length} Layer 1 tokens and ${layerTwo.length} Layer 2 aliases.`);
